import { readFileSync, mkdirSync, existsSync, writeFileSync, renameSync, rmSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'
import { resolve } from 'node:path'
import { execFileSync } from 'node:child_process'

const root = fileURLToPath(new URL('..', import.meta.url))
const dir = resolve(root, '.cache/fonts')
const fonts = JSON.parse(readFileSync(new URL('./fonts.json', import.meta.url), 'utf8'))
const sha256 = path => createHash('sha256').update(readFileSync(path)).digest('hex')
mkdirSync(dir, { recursive: true })
for (const font of fonts) {
  const path = resolve(dir, font.name)
  if (existsSync(path) && sha256(path) === font.sha256) continue
  const temporary = `${path}.download`
  try {
    execFileSync('curl', ['--fail', '--location', '--silent', '--show-error', '--retry', '3', '--output', temporary, font.url])
    if (sha256(temporary) !== font.sha256) throw new Error(`Font checksum mismatch: ${font.name}`)
    renameSync(temporary, path)
    console.log(`Installed ${font.name}`)
  } finally {
    rmSync(temporary, { force: true })
  }
}
writeFileSync(resolve(dir, 'README.txt'), 'Generated by pnpm setup:fonts. Sources and checksums: scripts/fonts.json.\n')
console.log(`Fonts ready: ${dir}`)
